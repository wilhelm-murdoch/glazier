// TestEndToEndProvisioning exercises the tmux client against a real tmux server
// on a throwaway socket. It is skipped when tmux is not installed. Unlike the
// rest of the suite (which fakes the command factory), this test issues real
// tmux commands and parses real tmux output, guarding the parts most likely to
// drift against new tmux versions: output formats, base-index logic, and the
// wait-for synchronisation.
func TestEndToEndProvisioning(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	socket := fmt.Sprintf("glaze-e2e-%d", os.Getpid())

	client, err := NewClient("", socket, discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	// Ensure the throwaway server is always torn down.
	t.Cleanup(func() {
		// The socket name is generated by this test, not user input.
		_ = exec.Command("tmux", "-L", socket, "kill-server").Run() //nolint:gosec // G204
	})

	dir := t.TempDir()

	session, err := client.NewSession("e2e", dir)
	assert.NoError(t, err)
	assert.NotNil(t, session)
	assert.Equal(t, "e2e", session.Name)

	running, err := client.IsRunning()
	assert.NoError(t, err)
	assert.True(t, running)
	assert.True(t, hasSession(t, client, "e2e"))

	// Session-scoped option round-trips through tmux.
	assert.NoError(t, session.SetOption("history-limit", "4242"))
	option, err := client.GetOption(session.Target(), "history-limit", "session")
	assert.NoError(t, err)
	assert.Contains(t, option, "4242")

	// Create a window with its own starting directory and split it.
	windowDir := t.TempDir()
	window, err := session.NewWindow("editor", windowDir)
	assert.NoError(t, err)
	assert.Equal(t, "editor", window.Name)

	windows, err := client.Windows(session)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(windows, func(w *Window) bool {
		return w.Name == "editor"
	}))

	defaultPane, err := firstPaneOf(client, window)
	assert.NoError(t, err)
	assert.NotNil(t, defaultPane)
	// The window's default pane should inherit the window's starting directory.
	// tmux reports the symlink-resolved path, so compare against that.
	resolvedDir, err := filepath.EvalSymlinks(windowDir)
	assert.NoError(t, err)
	assert.Equal(t, resolvedDir, defaultPane.StartingDirectory)

	pane, err := window.Split(defaultPane.Target(), "shell", dir)
	assert.NoError(t, err)
	assert.Equal(t, "shell", pane.Name)

	panes, err := client.Panes(window)
	assert.NoError(t, err)
	assert.Equal(t, 2, len(panes))

	// Run must return only after every command but the last has finished, so the marker exists at once.
	runner, err := client.NewCommandRunner(0)
	assert.NoError(t, err)

	marker := filepath.Join(dir, "done.marker")
	runWithTimeout(t, 10*time.Second, func() error {
		return runner.Run(pane.Target(), []string{fmt.Sprintf("touch '%s'", marker), "true"})
	})
	assert.FileExists(t, marker)

	// Tear the session down explicitly and confirm it is gone.
	assert.NoError(t, client.KillSessionByName("e2e"))
	assert.False(t, hasSession(t, client, "e2e"))
}

// TestEndToEndHostileNames creates a session, window and pane with names that
// tmux escapes in -F output and reads each name back. It guards the q: formats
// and the splitter against the tmux version under test. tmux 3.4 escapes a $
// that starts a variable name a second time, so run it on 3.4 as well.
func TestEndToEndHostileNames(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	socket := fmt.Sprintf("glaze-e2e-names-%d", os.Getpid())

	client, err := NewClient("", socket, discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	t.Cleanup(func() {
		// The socket name is generated by this test, not user input.
		_ = exec.Command("tmux", "-L", socket, "kill-server").Run() //nolint:gosec // G204
	})

	// TestEndToEndRewrittenNames covers the characters that glaze replaces.
	const (
		sessionName = `s;1 x;`
		windowName  = `w;1 $HOME;`
		paneName    = `p;1 ${x};`
	)

	session, err := client.NewSession(sessionName, t.TempDir())
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, sessionName, session.Name)

	found, err := client.FindSessionByName(sessionName)
	if assert.NoError(t, err) {
		assert.Equal(t, session.Id, found.Id)
	}

	// No client is attached, so tmux reports the only session on the server.
	current, err := client.CurrentSession()
	if assert.NoError(t, err) {
		assert.Equal(t, sessionName, current.Name)
	}

	window, err := session.NewWindow(windowName, "")
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, windowName, window.Name)

	windows, err := client.Windows(session)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(windows, func(w *Window) bool {
		return w.Name == windowName
	}), "window name did not round-trip")

	defaultPane, err := firstPaneOf(client, window)
	if !assert.NoError(t, err) {
		return
	}

	_, err = window.Split(defaultPane.Target(), paneName, "")
	assert.NoError(t, err)

	panes, err := client.Panes(window)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(panes, func(p *Pane) bool {
		return p.Name == paneName
	}), "pane name did not round-trip")
}

// TestEndToEndRewrittenNames uses names that tmux would rewrite. A session must be found
// and killed again by the name glaze was given, and window and pane names come back sanitised.
func TestEndToEndRewrittenNames(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	socket := fmt.Sprintf("glaze-e2e-rewrite-%d", os.Getpid())

	client, err := NewClient("", socket, discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	t.Cleanup(func() {
		// The socket name is generated by this test, not user input.
		_ = exec.Command("tmux", "-L", socket, "kill-server").Run() //nolint:gosec // G204
	})

	for _, name := range []string{"a.b", "a:b", `a\b`, "p$x", "p${x}", "tab\tx"} {
		t.Run(name, func(t *testing.T) {
			session, err := client.NewSession(name, t.TempDir())
			if !assert.NoError(t, err) {
				return
			}

			assert.True(t, hasSession(t, client, name), "has-session with the requested name")

			found, err := client.FindSessionByName(name)
			if assert.NoError(t, err) {
				assert.Equal(t, session.Id, found.Id)
			}

			assert.NoError(t, client.KillSessionByName(name))
			assert.False(t, hasSession(t, client, name), "session still running after kill")
		})
	}

	session, err := client.NewSession("names", t.TempDir())
	if !assert.NoError(t, err) {
		return
	}

	window, err := session.NewWindow("w\\z\tq", "")
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, "w-z-q", window.Name)

	windows, err := client.Windows(session)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(windows, func(w *Window) bool {
		return w.Name == "w-z-q"
	}), "sanitised window name did not round-trip")

	defaultPane, err := firstPaneOf(client, window)
	if !assert.NoError(t, err) {
		return
	}

	pane, err := window.Split(defaultPane.Target(), "p\\z\tq", "")
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, "p-z-q", pane.Name)

	panes, err := client.Panes(window)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(panes, func(p *Pane) bool {
		return p.Name == "p-z-q"
	}), "sanitised pane title did not round-trip")
}

