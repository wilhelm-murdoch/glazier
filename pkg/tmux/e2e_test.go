// TestEndToEndFormatSequencesInNames checks that tmux keeps #{...} and #X in
// names, titles and directories literally instead of expanding them.
func TestEndToEndFormatSequencesInNames(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	socket := fmt.Sprintf("glaze-e2e-format-%d", os.Getpid())

	client, err := NewClient("", socket, discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	t.Cleanup(func() {
		// The socket name is generated by this test, not user input.
		_ = exec.Command("tmux", "-L", socket, "kill-server").Run() //nolint:gosec // G204
	})

	dir := filepath.Join(t.TempDir(), "d#{session_name}")
	assert.NoError(t, os.Mkdir(dir, 0o750))
	resolvedDir, err := filepath.EvalSymlinks(dir)
	assert.NoError(t, err)

	session, err := client.NewSession("s#{host_short}", dir)
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, "s#{host_short}", session.Name)
	assert.True(t, hasSession(t, client, "s#{host_short}"))

	window, err := session.NewWindow("w#{session_name} a#Sb #[fg=red]x", dir)
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, "w#{session_name} a#Sb #[fg=red]x", window.Name)

	defaultPane, err := firstPaneOf(client, window)
	if !assert.NoError(t, err) {
		return
	}
	assert.Equal(t, resolvedDir, defaultPane.StartingDirectory)

	pane, err := window.Split(defaultPane.Target(), "p#{pane_id}", dir)
	if !assert.NoError(t, err) {
		return
	}
	splitDir, err := filepath.EvalSymlinks(pane.StartingDirectory)
	assert.NoError(t, err)
	assert.Equal(t, resolvedDir, splitDir)

	panes, err := client.Panes(window)
	assert.NoError(t, err)
	assert.True(t, slices.ContainsFunc(panes, func(p *Pane) bool {
		return p.Name == "p#{pane_id}"
	}), "pane title did not round-trip")
}

// TestEndToEndCommandRunner runs commands that a line editor or the tmux argument parser would change.
// It uses the default shell of the machine, so each developer and CI runner tests a different shell.
func TestEndToEndCommandRunner(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	socket := fmt.Sprintf("glaze-e2e-runner-%d", os.Getpid())

	client, err := NewClient("", socket, discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	t.Cleanup(func() {
		// The socket name is generated by this test, not user input.
		_ = exec.Command("tmux", "-L", socket, "kill-server").Run() //nolint:gosec // G204
	})

	dir := t.TempDir()
	session, err := client.NewSession("runner", dir)
	assert.NoError(t, err)

	window, err := session.NewWindow("w", dir)
	assert.NoError(t, err)

	pane, err := firstPaneOf(client, window)
	assert.NoError(t, err)

	t.Run("runs each command as written", func(t *testing.T) {
		runner, err := client.NewCommandRunner(0)
		assert.NoError(t, err)

		out := filepath.Join(dir, "out")
		commands := []string{
			"sleep 1 &",
			"echo wow!x > " + out + ";",
			// A real tab and a real newline, which a line editor would complete or split.
			"printf 'a\tb\n' >> " + out + " # a comment",
			"-x 2>/dev/null; echo dash >> " + out,
			"echo " + strings.Repeat("A", 5000) + " >> " + out,
			"echo end >> " + out,
		}
		runWithTimeout(t, 10*time.Second, func() error {
			return runner.Run(pane.Target(), commands)
		})

		// The last command runs after Run returns.
		want := "wow!x\na\tb\ndash\n" + strings.Repeat("A", 5000) + "\nend\n"
		assert.Eventually(t, func() bool {
			got, _ := os.ReadFile(out) //nolint:gosec // G304: the path is in a test directory.
			return string(got) == want
		}, 10*time.Second, 50*time.Millisecond)

		buffers, err := exec.Command("tmux", "-L", socket, "list-buffers").Output() //nolint:gosec // G204
		assert.NoError(t, err)
		assert.Empty(t, string(buffers))
	})

	t.Run("runs the commands after a syntax error", func(t *testing.T) {
		runner, err := client.NewCommandRunner(0)
		assert.NoError(t, err)

		out := filepath.Join(dir, "after")
		runWithTimeout(t, 10*time.Second, func() error {
			return runner.Run(pane.Target(), []string{"if then", `echo "unclosed`, "echo after > " + out, "true"})
		})
		assert.FileExists(t, out)
	})

	t.Run("stops waiting when the shell exits", func(t *testing.T) {
		exiting, err := window.Split(pane.Target(), "exiting", dir)
		assert.NoError(t, err)

		runner, err := client.NewCommandRunner(0)
		assert.NoError(t, err)

		done := make(chan error, 1)
		go func() { done <- runner.Run(exiting.Target(), []string{"exit", "true"}) }()

		select {
		case err := <-done:
			assert.ErrorIs(t, err, ErrPaneExited)
		case <-time.After(10 * time.Second):
			t.Fatal("Run did not return after the shell exited")
		}
	})

	t.Run("stops waiting after the timeout", func(t *testing.T) {
		runner, err := client.NewCommandRunner(200 * time.Millisecond)
		assert.NoError(t, err)

		done := make(chan error, 1)
		go func() { done <- runner.Run(pane.Target(), []string{"sleep 5", "true"}) }()

		select {
		case err := <-done:
			assert.ErrorIs(t, err, ErrCommandTimeout)
		case <-time.After(10 * time.Second):
			t.Fatal("Run did not return after the timeout")
		}
	})
}

// TestEndToEndUnreachableServer checks that a socket glaze cannot open is not reported as a missing session.
func TestEndToEndUnreachableServer(t *testing.T) {
	if _, err := exec.LookPath("tmux"); err != nil {
		t.Skip("tmux is not installed; skipping end-to-end test")
	}

	if os.Geteuid() == 0 {
		t.Skip("root ignores directory permissions, so the socket stays reachable")
	}

	// A socket path must be short, and the macOS temp directory is too long.
	dir, err := os.MkdirTemp("/tmp", "glaze-e2e-")
	assert.NoError(t, err)
	socket := filepath.Join(dir, "sock")

	client, err := NewClient(socket, "", discardLogger)
	if err != nil {
		t.Fatalf("could not create client: %v", err)
	}

	_, err = client.NewSession("held", t.TempDir())
	assert.NoError(t, err)

	t.Cleanup(func() {
		_ = os.Chmod(dir, 0o700) //nolint:gosec // G302: the test restores its own directory.
		// The socket path is generated by this test, not user input.
		_ = exec.Command("tmux", "-S", socket, "kill-server").Run() //nolint:gosec // G204
		_ = os.RemoveAll(dir)
	})

	assert.NoError(t, os.Chmod(dir, 0o000))

	exists, err := client.HasSession("held")
	assert.False(t, exists)
	assert.ErrorIs(t, err, ErrUnreachable)
	assert.ErrorContains(t, err, "Permission denied")

	running, err := client.IsRunning()
	assert.False(t, running)
	assert.ErrorIs(t, err, ErrUnreachable)

	// With access again, the same session is found.
	assert.NoError(t, os.Chmod(dir, 0o700)) //nolint:gosec // G302: the test restores its own directory.
	assert.True(t, hasSession(t, client, "held"))
}

// hasSession reports whether the session exists and fails the test when tmux cannot answer.
func hasSession(t *testing.T, client *Client, name string) bool {
	t.Helper()

	exists, err := client.HasSession(name)
	assert.NoError(t, err)

	return exists
}

// firstPaneOf returns the base-index pane of the given window.
func firstPaneOf(client *Client, window *Window) (*Pane, error) {
	panes, err := client.Panes(window)
	if err != nil {
		return nil, err
	}

	if len(panes) == 0 {
		return nil, fmt.Errorf("no pane found for window %q", window.Name)
	}

	return slices.MinFunc(panes, func(x, y *Pane) int { return int(x.Id) - int(y.Id) }), nil
}

// runWithTimeout fails the test if fn does not return within d, preventing a
// hung wait-for from stalling the whole suite.
func runWithTimeout(t *testing.T, d time.Duration, fn func() error) {
	t.Helper()
	done := make(chan error, 1)
	go func() { done <- fn() }()

	select {
	case err := <-done:
		assert.NoError(t, err)
	case <-time.After(d):
		t.Fatalf("operation did not complete within %s", d)
	}
}
